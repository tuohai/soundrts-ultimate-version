@pytest.mark.parametrize("locale", LOCALES)
def test_every_de_civ_bonus_is_present(locale, de_data, locale_blocks):
    """Every DE civ bonus must appear as its own line in our intro."""
    english = locale == "ui"
    blocks = locale_blocks.get(locale, {})
    de_loc = de_data.get(locale, {})
    problems = []
    for key, cid in CIV_ID.items():
        d = de_loc.get(key)
        assert d is not None, f"{locale}: no DE reference data for {key}"
        lines = blocks.get(cid)
        assert lines, f"{locale}/{key}: intro {cid} missing"
        body = [canon(l, english) for l in lines[2:-1]]
        for bonus in d["bonuses"]:
            c = canon(bonus, english)
            assert c in body, f"{locale}/{key}: missing bonus {bonus!r}"
        for tech in d["techs"]:
            c = canon(tech_effect_of(tech), english)
            assert c in body, f"{locale}/{key}: missing tech effect {tech!r}"
    assert not problems


@pytest.mark.parametrize("locale", LOCALES)
def test_no_extra_intro_lines(locale, de_data, locale_blocks):
    """Our intro must carry exactly the DE bonus + tech-effect lines."""
    english = locale == "ui"
    blocks = locale_blocks.get(locale, {})
    de_loc = de_data.get(locale, {})
    for key, cid in CIV_ID.items():
        d = de_loc[key]
        lines = blocks[cid]
        expected = 2 + len(d["bonuses"]) + len(d["techs"]) + 1
        assert len(lines) == expected, (
            f"{locale}/{key}: {len(lines)} lines, DE blurb implies {expected}"
        )
        canons = [canon(b, english) for b in d["bonuses"]]
        canons += [canon(tech_effect_of(t), english) for t in d["techs"]]
        cand = [canon(l, english) for l in lines[2:-1]]
        edges = [[j for j, l in enumerate(cand) if c == l] for c in canons]
        size, match_r = _max_matching(edges, len(cand))
        assert size == len(canons), (
            f"{locale}/{key}: only {size}/{len(canons)} DE lines matched"
        )
        for j, u in enumerate(match_r):
            assert u != -1, f"{locale}/{key}: extra line {lines[2 + j]!r}"


@pytest.mark.parametrize("locale", LOCALES)
def test_team_bonus_matches_de(locale, de_data, locale_blocks):
    english = locale == "ui"
    blocks = locale_blocks.get(locale, {})
    de_loc = de_data.get(locale, {})
    for key, cid in CIV_ID.items():
        d = de_loc[key]
        our_line = blocks[cid][-1]
        assert canon(d["team"], english) == canon(_team_core(our_line), english), (
            f"{locale}/{key}: team bonus {our_line!r} != DE {d['team']!r}"
        )


@pytest.mark.parametrize("locale", LOCALES)
def test_unique_units_and_techs_are_named(locale, de_data, locale_blocks):
    english = locale == "ui"
    blocks = locale_blocks.get(locale, {})
    de_loc = de_data.get(locale, {})
    for key, cid in CIV_ID.items():
        d = de_loc[key]
        uu_line, ut_line = blocks[cid][0], blocks[cid][1]
        for uu in d["uu_names"]:
            assert canon(uu, english) in canon(uu_line, english), (
                f"{locale}/{key}: unique unit {uu!r} not named in {uu_line!r}"
            )
        for tn in d["tech_names"]:
            assert canon(tn, english) in canon(ut_line, english), (
                f"{locale}/{key}: unique tech {tn!r} not named in {ut_line!r}"
            )


@pytest.mark.parametrize("locale", LOCALES)
def test_english_intro_speaks_numbers_out(locale, locale_blocks):
    """The English intros are spoken by a TTS voice, so they spell out
    the numbers and never use the '%' sign or raw digits."""
    if locale != "ui":
        pytest.skip("English only")
    blocks = locale_blocks.get(locale, {})
    for intro_id, lines in blocks.items():
        for line in lines:
            assert not re.search(r"\d", line), (
                f"{locale}/{intro_id}: raw digit in {line!r}"
            )
            assert "%" not in line, (
                f"{locale}/{intro_id}: raw percent sign in {line!r}"
            )
