WORD_NUM = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5,
    "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11,
    "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
    "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19,
    "twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60,
    "seventy": 70, "eighty": 80, "ninety": 90,
}


def _wordnum(w: str):
    """'twenty-five' -> 25, 'fifty' -> 50, otherwise None."""
    if "-" in w:
        parts = w.split("-")
        vals = [_wordnum(p) for p in parts]
        if all(v is not None for v in vals):
            return sum(vals)
        return None
    return WORD_NUM.get(w)


def _read_num(toks, i, english):
    """Read one number at ``toks[i]`` -> (value, next_index, pct, sign)."""
    t = toks[i]
    m = re.match(r"^([+-]?)(\d+)(%?)([^\w%]*)$", t)
    if m:
        return int(m.group(2)), i + 1, bool(m.group(3)), m.group(1)
    if not english:
        return None, i, False, ""
    vals = []
    j = i
    while j < len(toks):
        w = re.sub(r"[^\w%-].*$", "", toks[j])
        if w.endswith("%"):
            w = w[:-1]
        w = w.strip("-")
        if w == "hundred":
            vals.append(100)
            j += 1
            continue
        v = _wordnum(w)
        if v is None:
            break
        vals.append(v)
        j += 1
    if not vals:
        return None, i, False, ""
    cur = 0
    for v in vals:
        if v == 100:
            cur = (cur if cur else 1) * 100
        else:
            cur += v
    return cur, j, False, ""


def _parse_numexpr(toks, i, english):
    """Parse one numeric expression -> (canonical_text, next_index)."""
    n = len(toks)
    word_sign = ""
    if english and toks[i] in ("plus", "minus"):
        word_sign = "-" if toks[i] == "minus" else "+"
        i += 1

    vals, signs, pcts = [], [], []
    while True:
        val, j, pct, dsign = _read_num(toks, i, english)
        if val is None:
            if not vals:
                return None, i
            break
        vals.append(val)
        signs.append(dsign)
        pcts.append(pct)
        i = j
        if i + 1 < n and toks[i] == "/":
            i += 1
            continue
        break

    percent = any(pcts)
    less = False
    if i < n and toks[i].rstrip(".,;:!?") == "percent":
        percent = True
        i += 1
    if i < n and toks[i].rstrip(".,;:!?") == "less":
        less = True
        i += 1

    if percent:
        neg = less or (signs and signs[0] == "-")
        body = ("-" if neg else "") + "/".join(str(v) for v in vals) + "%"
    else:
        parts = []
        for v, s in zip(vals, signs):
            if s == "-" or (word_sign == "-" and s == ""):
                parts.append("-%d" % v)
            else:
                parts.append("%d" % v)
        body = "/".join(parts)
    return body, i


def _fold_numbers(text: str, english: bool) -> str:
    """Fold the spoken / DE numeric notation into one canonical form."""
    text = text.lower()
    text = text.replace("\u2212", "-")
    text = re.sub(r"([+-])\s+(\d)", r"\1\2", text)
    text = re.sub(r"\s*/\s*", " / ", text)

    toks = text.split()
    out = []
    i = 0
    while i < len(toks):
        body, j = _parse_numexpr(toks, i, english)
        if body is not None:
            out.append(body)
            i = j
            continue
        out.append(toks[i])
        i += 1
    return " ".join(out)


def canon(text: str, english: bool = False) -> str:
    """Canonical comparable form of a bonus / effect / team line."""
    t = re.sub(r"<br\s*/?>", " ", text)
    t = re.sub(r"<[^>]+>", "", t)
    t = t.replace("\u00a0", " ").replace("\u2019", "'").strip()
    t = t.rstrip(".。．！!？? ")
    t = _fold_numbers(t, english)
    t = re.sub(r"\s+", " ", t).strip()
    t = t.rstrip(".。．！!？? ")
    t = t.lower()
    t = re.sub(r"[«»\"“”'`]", "", t)
    t = re.sub(r"\s*([,;:])\s*", r"\1", t)
    return re.sub(r"\s+", " ", t).strip()


def tech_effect_of(entry) -> str:
    if isinstance(entry, dict):
        return entry["effect"]
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", entry)
    return m.group(2) if m else entry


def tech_name_of(entry) -> str:
    if isinstance(entry, dict):
        return entry["name"]
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", entry)
    return m.group(1).strip() if m else entry.strip()


def _parse_blocks(text: str) -> dict[int, list[str]]:
    blocks: dict[int, list[str]] = {}
    current: int | None = None
    for raw in text.split("\n"):
        stripped = raw.strip()
        if not stripped or stripped.startswith(";"):
            continue
        head = re.match(r"^(\d{4})\s+(.*\S)$", raw)
        if head:
            current = int(head.group(1))
            if current in INTRO_IDS:
                blocks.setdefault(current, []).append(head.group(2).strip())
            continue
        if raw[:1] in " \t" and current in INTRO_IDS:
            blocks[current].append(stripped)
        else:
            current = None
    return blocks


def _max_matching(edges, n_right):
    """Kuhn's bipartite matching -> (size, match_r)."""
    match_r = [-1] * n_right

    def try_kuhn(u, seen):
        for v in edges[u]:
            if seen[v]:
                continue
            seen[v] = True
            if match_r[v] == -1 or try_kuhn(match_r[v], seen):
                match_r[v] = u
                return True
        return False

    size = 0
    for u in range(len(edges)):
        if try_kuhn(u, [False] * n_right):
            size += 1
    return size, match_r


